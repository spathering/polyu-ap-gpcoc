from typing import Protocol, Any

class RoomRepository(Protocol):
    generation: int
    def snapshot(self) -> tuple[int, Any]: ...
    def commit(self, expected_generation: int, value: Any) -> int: ...
    def query(self, collection: str, **equals) -> list: ...
    def get_receipt(self, account: str, command: str): ...
    def close(self): ...

class IdentityStore(RoomRepository, Protocol):
    pass
