return rule('sv.profile', {'actor', 'strength:amount', 'dexterity:amount', 'will:amount', 'hp:amount', 'pips:amount'}, function(r, actor, strength, dexterity, will, hp, pips)
  assert(r.matches(actor, 'sv.character'), 'SV_NOT_CHARACTER')
  assert(r.number(actor, 'approved') == 0, 'SV_PROFILE_LOCKED')
  assert(strength >= 2 and strength <= 12 and dexterity >= 2 and dexterity <= 12 and will >= 2 and will <= 12, 'SV_START_ATTRIBUTE_RANGE')
  assert(hp >= 1 and hp <= 6 and pips <= 6, 'SV_START_RESOURCE_RANGE')
  r.set(actor, 'str', strength)
  r.set(actor, 'strMax', strength)
  r.set(actor, 'dex', dexterity)
  r.set(actor, 'dexMax', dexterity)
  r.set(actor, 'wil', will)
  r.set(actor, 'wilMax', will)
  r.set(actor, 'maxHp', hp)
  r.set(actor, 'hp', hp)
  r.set(actor, 'pips', pips)
  r.set(actor, 'approved', 1)
  return {character=actor, approved=true}
end, {kp=true})
